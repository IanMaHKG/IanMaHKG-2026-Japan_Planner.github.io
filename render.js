/**
 * @file render.js
 * @description DOM INJECTION MODULE — populates every static section of the page
 * by reading from the global data objects and building HTML strings.
 *
 * DEPENDS ON (must be loaded before this file):
 *   - site-data.js     → window.SITE_DATA
 *   - itinerary-data.js → window.ITINERARY_DATA
 *
 * EXPORTS (global functions, called by script.js):
 *   - renderSiteContent()  Orchestrator: calls all five section renderers below.
 *   - renderOverview()     Populates #overview-grid (cards) and #route-stops (visual).
 *   - renderTips()         Populates #tips-grid with tip cards.
 *   - renderPacking()      Populates #packing-grid with packing category cards.
 *   - renderBudget()       Populates #budget-tbody with JPY rows + .converted-val cells.
 *   - renderHotels()       Populates #quick-leg-pills and #itinerary-hotels-grid.
 *   - renderItinerary()    Populates #timeline with all 12 day-card accordions.
 *   - toggleDay(header)    Accordion open/close for a day card; also on window.toggleDay
 *                          so HTML onclick="toggleDay(this)" can reach it.
 *   - initDayCards()       Opens the first day card by default after render.
 *
 * BILINGUAL PATTERN:
 *   Every piece of text is wrapped in <span class="lang-en"> and <span class="lang-zh">.
 *   CSS on body.lang-en / body.lang-zh-hk controls visibility (defined in style.css).
 *
 * TO EDIT CONTENT: change site-data.js or itinerary-data.js — do NOT edit this file.
 * TO CHANGE LAYOUT: edit the template literals inside each render function below.
 */


/* ─── Orchestrator ─── */
function renderSiteContent() {
  renderOverview();
  renderTips();
  renderPacking();
  renderBudget();
  renderHotels();
}


/* ─── Overview Section ─── */
function renderOverview() {
  if (!window.SITE_DATA || !window.SITE_DATA.overview) return;
  const data = window.SITE_DATA.overview;

  const gridEl = document.getElementById('overview-grid');
  if (gridEl && data.cards) {
    gridEl.innerHTML = data.cards.map(card => `
      <div class="overview-card" id="${card.id}">
        <div class="ov-icon">${card.icon}</div>
        <h3>
          <span class="lang-en">${card.title.en}</span>
          <span class="lang-zh">${card.title.zh}</span>
        </h3>
        <p class="lang-en">${card.desc.en}</p>
        <p class="lang-zh">${card.desc.zh}</p>
      </div>
    `).join('');
  }

  const stopsEl = document.getElementById('route-stops');
  if (stopsEl && data.routeStops) {
    stopsEl.innerHTML = data.routeStops.map(stop => `
      <div class="route-stop jr-station-node" data-stop="${stop.label}">
        <!-- Above the line: Station Code + Kanji + Hiragana -->
        <div class="jr-station-top">
          <div class="jr-station-code" style="--code-color: ${stop.color};">
            <span class="jr-code-prefix">${stop.label}</span>
            <span class="jr-code-num">${stop.code}</span>
          </div>
          <div class="jr-station-kanji">${stop.kanji}</div>
          <div class="jr-station-kana">${stop.hiragana}</div>
        </div>

        <!-- Middle: Station Dot on the track -->
        <div class="jr-station-dot-wrapper">
          <div class="stop-dot ${stop.dotClass}" style="--dot-color: ${stop.color};">
            <span class="dot-inner-core"></span>
          </div>
        </div>

        <!-- Below the line: Romaji + Days Tag -->
        <div class="jr-station-bottom">
          <div class="jr-station-romaji">${stop.romaji}</div>
          <div class="jr-station-days">
            <span class="lang-en">${stop.days.en}</span>
            <span class="lang-zh">${stop.days.zh}</span>
          </div>
        </div>
      </div>
    `).join('');
  }
}


/* ─── Practical Tips Section ─── */
function renderTips() {
  if (!window.SITE_DATA || !window.SITE_DATA.tips) return;
  const tipsEl = document.getElementById('tips-grid');
  if (!tipsEl) return;

  tipsEl.innerHTML = window.SITE_DATA.tips.map(tip => {
    const itemsHtml = tip.items.map(item => `
      <li>
        <span class="lang-en">${item.en}</span>
        <span class="lang-zh">${item.zh}</span>
      </li>
    `).join('');

    return `
      <div class="tip-card" id="${tip.id}">
        <div class="tip-header">
          <span class="tip-icon">${tip.icon}</span>
          <h3>
            <span class="lang-en">${tip.title.en}</span>
            <span class="lang-zh">${tip.title.zh}</span>
          </h3>
        </div>
        <ul>
          ${itemsHtml}
        </ul>
      </div>
    `;
  }).join('');
}


