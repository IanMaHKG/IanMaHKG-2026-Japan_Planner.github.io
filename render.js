/* ─── Budget Table Section ─── */
function renderBudget() {
  if (!window.SITE_DATA || !window.SITE_DATA.budget) return;
  const tbodyEl = document.getElementById('budget-tbody');
  if (!tbodyEl) return;

  const data = window.SITE_DATA.budget;

  const rowsHtml = data.items.map(item => `
    <tr>
      <td>
        <span class="lang-en">${item.category.en}</span>
        <span class="lang-zh">${item.category.zh}</span>
      </td>
      <td>${item.jpy}</td>
      <td class="converted-val" data-min="${item.min}" data-max="${item.max}">
        ${item.initial}
      </td>
      <td>
        <span class="lang-en">${item.notes.en}</span>
        <span class="lang-zh">${item.notes.zh}</span>
      </td>
    </tr>
  `).join('');

  const totalHtml = `
    <tr class="budget-total">
      <td>
        <span class="lang-en">${data.total.category.en}</span>
        <span class="lang-zh">${data.total.category.zh}</span>
      </td>
      <td>${data.total.jpy}</td>
      <td class="converted-val budget-total-val" data-min="${data.total.min}" data-max="${data.total.max}">
        ${data.total.initial}
      </td>
      <td>
        <span class="lang-en">${data.total.notes.en}</span>
        <span class="lang-zh">${data.total.notes.zh}</span>
      </td>
    </tr>
  `;

  tbodyEl.innerHTML = rowsHtml + totalHtml;
}


/* ─── Hotels & Ryokan Section ─── */
function renderHotels() {
  if (!window.SITE_DATA || !window.SITE_DATA.hotels) return;
  const data = window.SITE_DATA.hotels;

  // Quick leg pills
  const quickLegsEl = document.getElementById('quick-leg-pills');
  if (quickLegsEl && data.quickLegs) {
    quickLegsEl.innerHTML = data.quickLegs.map(leg => `
      <button class="leg-pill ${leg.active ? 'active' : ''}" data-dest="${leg.dest}" data-checkin="${leg.checkin}" data-checkout="${leg.checkout}">
        <span class="lang-en">${leg.label.en}</span>
        <span class="lang-zh">${leg.label.zh}</span>
      </button>
    `).join('');
  }

  // Curated hotel leg cards
  const gridEl = document.getElementById('itinerary-hotels-grid');
  if (gridEl && data.legs) {
    gridEl.innerHTML = data.legs.map(leg => {
      const tagsHtml = leg.tags.map(tag => `<span>${tag}</span>`).join('');
      const badgeCls = leg.badgeClass ? ` ${leg.badgeClass}` : '';
      const cardCls = leg.highlight ? 'hotel-leg-card highlight-card' : 'hotel-leg-card';
      const bookingUrl = `https://www.booking.com/searchresults.html?ss=${encodeURIComponent(leg.dest)}&checkin=${leg.checkin}&checkout=${leg.checkout}&group_adults=3&no_rooms=1`;

      return `
        <div class="${cardCls}">
          <div class="hotel-leg-badge${badgeCls}">
            <span class="lang-en">${leg.nights.en}</span>
            <span class="lang-zh">${leg.nights.zh}</span>
          </div>
          <div class="hotel-leg-body">
            <h4>
              <span class="lang-en">${leg.title.en}</span>
              <span class="lang-zh">${leg.title.zh}</span>
            </h4>
            <p class="hotel-leg-dates">${leg.dates}</p>
            <p class="hotel-leg-desc">
              <span class="lang-en">${leg.desc.en}</span>
              <span class="lang-zh">${leg.desc.zh}</span>
            </p>
            <div class="hotel-leg-tags">
              ${tagsHtml}
            </div>
            <a href="${bookingUrl}" target="_blank" rel="noopener" class="hotel-leg-btn" data-dest="${leg.dest}" data-checkin="${leg.checkin}" data-checkout="${leg.checkout}">
              <span class="lang-en">${leg.btnText.en}</span>
              <span class="lang-zh">${leg.btnText.zh}</span>
            </a>
          </div>
        </div>
      `;
    }).join('');
  }
}


/* ─── Itinerary Timeline ─── */
function renderItinerary() {
  const container = document.getElementById('timeline');
  if (!container || !window.ITINERARY_DATA) return;

  const html = window.ITINERARY_DATA.map(day => {
    // Build tag chips
    const tagsHtml = day.tags.map(tag => {
      if (tag.type === 'city') {
        return `<span class="tag tag-city">${tag.text}</span>`;
      } else if (tag.type === 'transport') {
        return `<span class="tag tag-transport">${tag.text}</span>`;
      } else if (tag.type === 'pace') {
        return `
          <span class="tag tag-pace">
            <span class="lang-en">${tag.en}</span>
            <span class="lang-zh">${tag.zh}</span>
          </span>`;
      } else if (tag.type === 'special') {
        if (tag.text) {
          return `<span class="tag tag-special">${tag.text}</span>`;
        } else {
          return `
            <span class="tag tag-special">
              <span class="lang-en">${tag.en}</span>
              <span class="lang-zh">${tag.zh}</span>
            </span>`;
        }
      }
      return '';
    }).join('');

    // Build time blocks
    const blocksHtml = day.blocks.map(block => {
      const mealHtml = block.activity.meal ? `
        <div class="meal-rec">
          <span class="meal-icon">${block.activity.meal.icon}</span>
          <span class="lang-en">${block.activity.meal.en}</span>
          <span class="lang-zh">${block.activity.meal.zh}</span>
        </div>` : '';

      return `
        <div class="timeline-block">
          <div class="time-badge">
            <span class="lang-en">${block.time.en}</span>
            <span class="lang-zh">${block.time.zh}</span>
          </div>
          <div class="activity">
            <h4>
              <span class="lang-en">${block.activity.title.en}</span>
              <span class="lang-zh">${block.activity.title.zh}</span>
            </h4>
            <p class="lang-en">${block.activity.desc.en}</p>
            <p class="lang-zh">${block.activity.desc.zh}</p>
            ${mealHtml}
          </div>
        </div>`;
    }).join('');

    // Optional daily tip
    const tipHtml = day.tip ? `
      <div class="day-tip">
        <span class="lang-en">${day.tip.en}</span>
        <span class="lang-zh">${day.tip.zh}</span>
      </div>` : '';

    return `
      <!-- ════ DAY ${day.dayNum} ════ -->
      <div class="day-card" data-region="${day.region}" id="${day.id}">
        <div class="day-header" onclick="toggleDay(this)">
          <div class="day-badge">
            <span class="day-num">${day.dayNum}</span>
            <span class="day-date">${day.date}</span>
          </div>
          <div class="day-info">
            <h3>
              <span class="lang-en">${day.title.en}</span>
              <span class="lang-zh">${day.title.zh}</span>
            </h3>
            <div class="day-tags">
              ${tagsHtml}
            </div>
          </div>
          <div class="day-chevron">▼</div>
        </div>
        <div class="day-body">
          ${blocksHtml}
          ${tipHtml}
        </div>
      </div>`;
  }).join('\n');

  container.innerHTML = html;
}


/* ─── Day Card Accordion ─── */
function toggleDay(header) {
  const card = header.closest('.day-card');
  const wasOpen = card.classList.contains('open');

  // Close all other open cards
  document.querySelectorAll('.day-card.open').forEach(c => {
    if (c !== card) c.classList.remove('open');
  });

  // Toggle current card
  card.classList.toggle('open', !wasOpen);

  // Smooth scroll into view when opening
  if (!wasOpen) {
    setTimeout(() => {
      card.scrollIntoView({ behavior: 'smooth', block: 'start' });
    }, 150);
  }
}

// Expose toggleDay to inline onclick handlers
window.toggleDay = toggleDay;


/* ─── Day Cards Init ─── */
function initDayCards() {
  // Open the first day card by default
  const firstCard = document.querySelector('.day-card');
  if (firstCard) firstCard.classList.add('open');
}
